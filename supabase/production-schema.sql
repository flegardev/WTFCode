    requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    analysis_profile VARCHAR(20) NOT NULL,
    job_kind VARCHAR(20) NOT NULL DEFAULT 'rescan' CHECK (job_kind IN ('initial', 'rescan')),
    state VARCHAR(20) NOT NULL DEFAULT 'queued' CHECK (state IN ('queued', 'running', 'completed', 'partial', 'failed')),
    attempt_count INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 3,
