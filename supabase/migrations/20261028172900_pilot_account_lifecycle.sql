-- Additive pilot lifecycle upgrade. Review and back up before any hosted use.
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL DEFAULT 0;
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON users (LOWER(email));
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS sessions_user_index ON sessions(user_id);
CREATE TABLE IF NOT EXISTS account_link_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(190) NOT NULL,
 purpose VARCHAR(12) NOT NULL CHECK (purpose IN ('verify','reset')),
 attempts SMALLINT NOT NULL DEFAULT 0,
 available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 leased_until TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE account_link_requests ENABLE ROW LEVEL SECURITY;
CREATE TABLE IF NOT EXISTS account_tokens (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 purpose VARCHAR(12) NOT NULL CHECK (purpose IN ('verify','reset')),
 token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at TIMESTAMPTZ NOT NULL,
 consumed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS account_tokens_user_index ON account_tokens(user_id, purpose);
CREATE TABLE IF NOT EXISTS worker_heartbeats (
 worker_id VARCHAR(100) PRIMARY KEY,
 last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS storage_cleanup_tasks (
 project_id BIGINT PRIMARY KEY,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Optional, explicitly submitted structured feedback. No source/free-text fields.
CREATE TABLE IF NOT EXISTS pilot_feedback (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 category VARCHAR(30) NOT NULL CHECK (category IN ('confusing','incorrect','scan_failure','missing_feature','usability','general')),
 area VARCHAR(20) NOT NULL CHECK (area IN ('overview','architecture','questions','change','account','other')),
 usefulness SMALLINT NOT NULL CHECK (usefulness BETWEEN 1 AND 5),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS pilot_feedback_user_index ON pilot_feedback(user_id);
